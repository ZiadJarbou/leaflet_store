export function currencyForCountryCode(countryCode: string) {
  const currencyCode = COUNTRY_TO_CURRENCY_CODE[String(countryCode || '').trim().toUpperCase()];
  return currencyCode ? WORLD_CURRENCIES.find(currency => currency.code === currencyCode) || null : null;
}

export function defaultCurrencySymbolForCountryCode(countryCode: string) {
  const currency = currencyForCountryCode(countryCode);
  return currency ? currency.altSymbol || currency.symbol : '';
}
